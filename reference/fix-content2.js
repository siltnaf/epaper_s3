async function fixContent() {
  const { rows: books } = await pool.query("SELECT id, title FROM books WHERE content IS NULL");
  console.log(`📚 Found ${books.length} books with null content\n`);
  
  const storyMap = new Map();
  for (const s of stories) {
    storyMap.set(s.title, s.content);
  }
  
  let fixed = 0;
  let missing = 0;
  
  for (const book of books) {
    const content = storyMap.get(book.title);
    if (!content) {
      console.log(`⚠️  No content found for: ${book.title}`);
      missing++;
      continue;
    }
    
    await pool.query('UPDATE books SET content = $1 WHERE id = $2', [content, book.id]);
    console.log(`✅ Fixed: ${book.title} (id: ${book.id})`);
    fixed++;
  }
  
  console.log(`\n🎉 Done! Fixed: ${fixed}, Missing source: ${missing}`);
  await pool.end();
}

